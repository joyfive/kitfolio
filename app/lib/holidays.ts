/** 공휴일 데이터를 보유한 연도인지 (UI에서 안내 표시용) */
export function hasHolidayData(year: number): boolean {
  return year in KR_HOLIDAYS;
}

const pad = (n: number) => String(n).padStart(2, "0");

/** 해당 날짜(year, month=1~12, day)가 공휴일인지 */
export function isKrHoliday(year: number, month: number, day: number): boolean {
  const list = KR_HOLIDAYS[year];
  if (!list) return false;
  return list.includes(`${pad(month)}-${pad(day)}`);
}
